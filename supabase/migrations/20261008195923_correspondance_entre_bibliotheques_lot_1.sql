-- ─────────────────────────────────────────────────────────────────────
-- 5. Vérifications
-- ─────────────────────────────────────────────────────────────────────
DO $g19_verif$
DECLARE v_e text := ''; t text; f text;
BEGIN
  FOREACH t IN ARRAY ARRAY['library_conversations', 'library_conversation_participants', 'library_messages', 'library_conversation_reads'] LOOP
    IF NOT EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                    WHERE n.nspname = 'public' AND c.relname = t AND c.relrowsecurity AND NOT c.relforcerowsecurity) THEN
      v_e := v_e || ' rls(' || t || ')';
    END IF;
    IF has_table_privilege('anon', 'public.' || t, 'SELECT')
       OR has_table_privilege('authenticated', 'public.' || t, 'INSERT')
       OR has_table_privilege('authenticated', 'public.' || t, 'UPDATE')
       OR has_table_privilege('authenticated', 'public.' || t, 'DELETE')
       OR NOT has_table_privilege('authenticated', 'public.' || t, 'SELECT') THEN
      v_e := v_e || ' droits-table(' || t || ')';
    END IF;
    IF (SELECT count(*) FROM pg_policies WHERE schemaname = 'public' AND tablename = t) <> 1 THEN
      v_e := v_e || ' politiques(' || t || ')';
    END IF;
  END LOOP;
  FOREACH f IN ARRAY ARRAY[
    'api.fn_correspondance_ouvrir(uuid, uuid, text, text, text)', 'api.fn_correspondance_envoyer(bigint, uuid, text, text)',
    'api.fn_correspondance_archiver(bigint, uuid, boolean)', 'api.fn_correspondance_lue(bigint)',
    'public.fn_correspondance_lit(bigint)'] LOOP
    IF NOT has_function_privilege('authenticated', f, 'EXECUTE') OR has_function_privilege('anon', f, 'EXECUTE')
       OR NOT has_function_privilege('service_role', f, 'EXECUTE')
       OR EXISTS (SELECT 1 FROM pg_proc p CROSS JOIN LATERAL aclexplode(p.proacl) a WHERE p.oid = f::regprocedure AND a.grantee = 0) THEN
      v_e := v_e || ' droits-portes(' || f || ')';
    END IF;
  END LOOP;
  FOREACH f IN ARRAY ARRAY[
    'public.fn_correspondance_coordonne(uuid)', 'public.fn_correspondance_langue(text, uuid)',
    'public.fn_correspondance_poser_message(bigint, uuid, text, text)'] LOOP
    IF has_function_privilege('authenticated', f, 'EXECUTE') OR has_function_privilege('anon', f, 'EXECUTE')
       OR EXISTS (SELECT 1 FROM pg_proc p CROSS JOIN LATERAL aclexplode(p.proacl) a WHERE p.oid = f::regprocedure AND a.grantee = 0) THEN
      v_e := v_e || ' droits-internes(' || f || ')';
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
              WHERE p.proname LIKE 'fn_correspondance_%' AND n.nspname IN ('api', 'public')
                AND (NOT p.prosecdef OR coalesce(p.proconfig::text, '') NOT LIKE '%search_path%')) THEN
    v_e := v_e || ' definer';
  END IF;
  IF v_e <> '' THEN
    RAISE EXCEPTION 'G19 lot 1 : vérification en échec :%', v_e;
  END IF;
  RAISE NOTICE 'G19 lot 1 : vérifications OK — quatre tables, cinq portes, trois aides fermées';
END
$g19_verif$;

