-- =====================================================================
-- AnarBib — G19 lot 1 : correspondance entre bibliothèques — les données
-- Date    : 2026-10-08
-- Ref     : backlog v34 G19 ; REGISTRE CORR-1 à CORR-6 (lot 0, décisions de
--           Xavier du 08/10/2026).
--
-- Ce que c'est. Une coordination écrit à une autre bibliothèque dans un FIL
-- de l'app ; chaque message garde son texte et sa langue. Rien de tel
-- n'existait : l'entraide est un aller-retour, les échanges sont une
-- demande suivie d'une réponse, le PEB et les assemblées sont des gestes
-- structurés. Ce lot pose les données, les règles d'écriture et de lecture,
-- rien à l'écran (lot 2), aucune notification (lot 3).
--
-- Les règles, décidées au lot 0 :
--   CORR-1  les coordinations seules lisent et écrivent, au nom de LEUR
--           bibliothèque ; ni les bibliothécaires, ni les lectrices ;
--   CORR-2  (lot 3) le courriel va à l'adresse collective de la bibliothèque ;
--   CORR-3  (lot 5) traduction automatique avec consentement — les colonnes
--           lang / body_i18n / i18n_status sont posées ici, vides ;
--   CORR-4  pas de réponse par courriel au début ;
--   CORR-5  l'onglet s'appelle « Correspondance » ;
--   CORR-6  l'administration du réseau NE LIT PAS la correspondance des
--           bibliothèques (sauf comme coordination d'une bibliothèque du
--           fil) : ce sont des lettres entre collectifs, pas un journal de
--           la plateforme. Réversible par une décision au REGISTRE, pas par
--           un correctif.
--
-- Les tables (schéma public ; toutes au flux COURT de la sauvegarde #BG2,
-- comme reader_library_messages : du texte écrit par des personnes).
--   library_conversations              un fil : sujet, qui l'a ouvert, dernier message
--   library_conversation_participants  une bibliothèque par ligne, archivage propre à
--                                      chacune (un fil archivé chez A reste vivant chez B ;
--                                      un message nouveau le rend à toutes)
--   library_messages                   un message : bibliothèque expéditrice, auteur·ice,
--                                      corps (1 à 4 000), langue (dix locales), traduction
--   library_conversation_reads         ce que chaque personne a lu (dernier message lu)
--
-- Écritures : par les RPC DEFINER du schéma api SEULEMENT (ouvrir, envoyer,
-- archiver, marquer lu) — aucun droit d'écriture pour authenticated sur les
-- tables ; lecture par une politique, une permissive par (rôle, commande)
-- (B10). Jamais de suppression : un fil s'archive. Limite d'envoi : 30
-- messages par personne et par 24 h (le modèle de send_message_to_reader).
-- Pas de table temporaire (cache PostgREST). Droits : chaque fonction neuve
-- REVOKE … FROM PUBLIC, anon, authenticated puis GRANT nommé (api et public
-- n'ont pas les mêmes privilèges par défaut ; gardes T10/T12).
-- Suite : tests/sql/correspondance_lot1_tests.sql.
-- =====================================================================

-- ─────────────────────────────────────────────────────────────────────
-- 1. Les tables
-- ─────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.library_conversations (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject          text NOT NULL CONSTRAINT library_conversations_subject_check
                     CHECK (btrim(subject) <> '' AND char_length(subject) <= 200),
  created_by       uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  last_message_at  timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.library_conversations IS
  'G19 lot 1 (08/10/2026) : un fil de correspondance entre bibliothèques (CORR-1). Lecture : les coordinations des '
  'bibliothèques participantes seulement, par politique ; écriture : api.fn_correspondance_* (DEFINER). Jamais supprimé, '
  'archivé par bibliothèque (participants). Sauvegarde #BG2 : flux court (texte écrit par des personnes).';
CREATE INDEX IF NOT EXISTS library_conversations_created_by_idx ON public.library_conversations (created_by);
CREATE INDEX IF NOT EXISTS library_conversations_dernier_idx ON public.library_conversations (last_message_at DESC);

CREATE TABLE IF NOT EXISTS public.library_conversation_participants (
  conversation_id  bigint NOT NULL REFERENCES public.library_conversations(id) ON DELETE CASCADE,
  library_id       uuid   NOT NULL REFERENCES public.libraries(id) ON DELETE CASCADE,
  joined_at        timestamptz NOT NULL DEFAULT now(),
  archived_at      timestamptz,
  PRIMARY KEY (conversation_id, library_id)
);
COMMENT ON TABLE public.library_conversation_participants IS
  'G19 lot 1 : les bibliothèques d''un fil, une par ligne — l''archivage est propre à chacune ; un message nouveau le lève '
  'pour toutes. Une table de participantes (et non deux colonnes A/B) : elle ouvre la porte aux fils de cercle.';
CREATE INDEX IF NOT EXISTS library_conversation_participants_library_idx
  ON public.library_conversation_participants (library_id, archived_at);

CREATE TABLE IF NOT EXISTS public.library_messages (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id  bigint NOT NULL REFERENCES public.library_conversations(id) ON DELETE CASCADE,
  library_id       uuid   NOT NULL REFERENCES public.libraries(id) ON DELETE CASCADE,   -- l'expéditrice
  author_id        uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  body             text NOT NULL CONSTRAINT library_messages_body_check
                     CHECK (char_length(btrim(body)) >= 1 AND char_length(body) <= 4000),
  lang             text NOT NULL CONSTRAINT library_messages_lang_check
                     CHECK (lang = ANY (ARRAY['pt-BR','fr','es','en','it','de','el','ca','eo','nl'])),
  body_i18n        jsonb,                                   -- lot 5 : { "<locale>": "<texte>" }, marquée automatique
  i18n_status      text NOT NULL DEFAULT 'none' CONSTRAINT library_messages_i18n_status_check
                     CHECK (i18n_status IN ('none', 'pending', 'done', 'error')),
  created_at       timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE public.library_messages IS
  'G19 lot 1 : un message d''un fil, au nom d''une bibliothèque participante, écrit par une de ses coordinations. '
  'Le texte reste tel qu''écrit, dans sa langue (lang, dix locales) ; body_i18n / i18n_status attendent le lot 5 '
  '(traduction avec consentement, CORR-3). Sauvegarde #BG2 : flux court.';
CREATE INDEX IF NOT EXISTS library_messages_conversation_idx ON public.library_messages (conversation_id, id);
CREATE INDEX IF NOT EXISTS library_messages_library_idx ON public.library_messages (library_id);
CREATE INDEX IF NOT EXISTS library_messages_author_idx ON public.library_messages (author_id, created_at);

CREATE TABLE IF NOT EXISTS public.library_conversation_reads (
  conversation_id       bigint NOT NULL REFERENCES public.library_conversations(id) ON DELETE CASCADE,
  user_id               uuid   NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  last_read_message_id  bigint NOT NULL DEFAULT 0,
  read_at               timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (conversation_id, user_id)
);
COMMENT ON TABLE public.library_conversation_reads IS
  'G19 lot 1 : ce que chaque personne a lu d''un fil (dernier message lu) — propre à la personne, pas à la bibliothèque.';
CREATE INDEX IF NOT EXISTS library_conversation_reads_user_idx ON public.library_conversation_reads (user_id);

DROP TRIGGER IF EXISTS trg_library_conversations_touch ON public.library_conversations;
CREATE TRIGGER trg_library_conversations_touch BEFORE UPDATE ON public.library_conversations
  FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();

-- ─────────────────────────────────────────────────────────────────────
-- 2. Qui coordonne, qui lit — deux aides
-- ─────────────────────────────────────────────────────────────────────
-- Une coordination ACTIVE de la bibliothèque, et elle seule (CORR-1, CORR-6) :
-- pas fn_team_caller_is_coordenador, qui ouvre à l'administration du réseau.
CREATE OR REPLACE FUNCTION public.fn_correspondance_coordonne(p_library_id uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.user_library_memberships m
     WHERE m.user_id = (SELECT auth.uid())
       AND m.library_id = p_library_id
       AND m.role = 'coordenador'
       AND m.status = 'active');
$$;
REVOKE EXECUTE ON FUNCTION public.fn_correspondance_coordonne(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.fn_correspondance_coordonne(uuid) TO service_role;

-- Lire un fil : être coordination d'une de ses bibliothèques. DEFINER : la
-- politique de chaque table l'appelle, et une politique qui relirait la table
-- des participantes sous sa propre politique tournerait en rond.
CREATE OR REPLACE FUNCTION public.fn_correspondance_lit(p_conversation_id bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.library_conversation_participants p
     WHERE p.conversation_id = p_conversation_id
       AND public.fn_correspondance_coordonne(p.library_id));
$$;
REVOKE EXECUTE ON FUNCTION public.fn_correspondance_lit(bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.fn_correspondance_lit(bigint) TO authenticated, service_role;

