-- ─────────────────────────────────────────────────────────────────────
-- 4. Les gestes (api, DEFINER) : ouvrir, envoyer, archiver, marquer lu
-- ─────────────────────────────────────────────────────────────────────
-- La langue d'un message : celle donnée, sinon celle du profil, sinon celle
-- de la bibliothèque, sinon pt-BR ; toujours l'une des dix.
CREATE OR REPLACE FUNCTION public.fn_correspondance_langue(p_lang text, p_library_id uuid)
RETURNS text
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
DECLARE v text;
BEGIN
  v := nullif(btrim(coalesce(p_lang, '')), '');
  IF v IS NULL THEN
    SELECT pr.preferred_language INTO v FROM public.profiles pr WHERE pr.id = (SELECT auth.uid());
  END IF;
  IF v IS NULL OR v = '' THEN
    SELECT l.default_locale INTO v FROM public.libraries l WHERE l.id = p_library_id;
  END IF;
  v := coalesce(nullif(v, ''), 'pt-BR');
  IF v <> ALL (ARRAY['pt-BR','fr','es','en','it','de','el','ca','eo','nl']) THEN
    RAISE EXCEPTION 'lang_invalid: %', v USING errcode = '22023', hint = 'error.correspondance.lang_invalid';
  END IF;
  RETURN v;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.fn_correspondance_langue(text, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.fn_correspondance_langue(text, uuid) TO service_role;

-- Poser un message : les contrôles communs à « ouvrir » et « envoyer ».
-- Appelée par les deux RPC, jamais par l'API.
CREATE OR REPLACE FUNCTION public.fn_correspondance_poser_message(p_conversation_id bigint, p_library_id uuid, p_corps text, p_lang text)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
DECLARE v_body text := btrim(coalesce(p_corps, '')); v_recent int; v_id bigint; v_lang text;
BEGIN
  IF char_length(v_body) < 1 THEN
    RAISE EXCEPTION 'empty_body' USING errcode = '22023', hint = 'error.correspondance.empty_body';
  END IF;
  IF char_length(v_body) > 4000 THEN
    RAISE EXCEPTION 'body_too_long' USING errcode = '22023', hint = 'error.correspondance.body_too_long';
  END IF;
  v_lang := public.fn_correspondance_langue(p_lang, p_library_id);
  -- Garde-fou large anti-boucle, le modèle de send_message_to_reader : une
  -- coordination est de confiance, trente messages par jour suffisent.
  SELECT count(*) INTO v_recent FROM public.library_messages m
   WHERE m.author_id = (SELECT auth.uid()) AND m.created_at > now() - interval '24 hours';
  IF v_recent >= 30 THEN
    RAISE EXCEPTION 'rate_limited' USING errcode = '53400', hint = 'error.correspondance.rate_limited';
  END IF;
  INSERT INTO public.library_messages (conversation_id, library_id, author_id, body, lang)
  VALUES (p_conversation_id, p_library_id, (SELECT auth.uid()), v_body, v_lang)
  RETURNING id INTO v_id;
  -- Un message nouveau rend le fil à toutes ses bibliothèques (archivage levé).
  UPDATE public.library_conversation_participants SET archived_at = NULL
   WHERE conversation_id = p_conversation_id AND archived_at IS NOT NULL;
  UPDATE public.library_conversations SET last_message_at = now() WHERE id = p_conversation_id;
  RETURN v_id;
END;
$$;
REVOKE EXECUTE ON FUNCTION public.fn_correspondance_poser_message(bigint, uuid, text, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.fn_correspondance_poser_message(bigint, uuid, text, text) TO service_role;

-- Ouvrir un fil : de MA bibliothèque (je la coordonne) vers une autre,
-- active ; le sujet et le premier message. Plusieurs fils sont possibles
-- entre deux mêmes bibliothèques, un par sujet, comme des lettres.
CREATE OR REPLACE FUNCTION api.fn_correspondance_ouvrir(p_library_id uuid, p_destinataire_id uuid, p_sujet text, p_corps text, p_lang text DEFAULT NULL)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
DECLARE v_sujet text := btrim(coalesce(p_sujet, '')); v_id bigint;
BEGIN
  IF NOT public.fn_correspondance_coordonne(p_library_id) THEN
    RAISE EXCEPTION 'not_coordinator' USING errcode = '42501', hint = 'error.correspondance.not_coordinator';
  END IF;
  IF p_destinataire_id IS NULL OR p_destinataire_id = p_library_id THEN
    RAISE EXCEPTION 'same_library' USING errcode = '22023', hint = 'error.correspondance.same_library';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.libraries l WHERE l.id = p_destinataire_id AND l.is_active = true) THEN
    RAISE EXCEPTION 'library_not_found' USING errcode = 'P0002', hint = 'error.correspondance.library_not_found';
  END IF;
  IF char_length(v_sujet) < 1 OR char_length(v_sujet) > 200 THEN
    RAISE EXCEPTION 'subject_required' USING errcode = '22023', hint = 'error.correspondance.subject_required';
  END IF;
  INSERT INTO public.library_conversations (subject, created_by) VALUES (v_sujet, (SELECT auth.uid()))
  RETURNING id INTO v_id;
  INSERT INTO public.library_conversation_participants (conversation_id, library_id)
  VALUES (v_id, p_library_id), (v_id, p_destinataire_id);
  PERFORM public.fn_correspondance_poser_message(v_id, p_library_id, p_corps, p_lang);
  PERFORM api.fn_correspondance_lue(v_id);
  RETURN v_id;
END;
$$;

-- Envoyer dans un fil, au nom d'une bibliothèque participante que je coordonne.
CREATE OR REPLACE FUNCTION api.fn_correspondance_envoyer(p_conversation_id bigint, p_library_id uuid, p_corps text, p_lang text DEFAULT NULL)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
DECLARE v_id bigint;
BEGIN
  IF NOT public.fn_correspondance_coordonne(p_library_id) THEN
    RAISE EXCEPTION 'not_coordinator' USING errcode = '42501', hint = 'error.correspondance.not_coordinator';
  END IF;
  -- « introuvable » et « pas dans ce fil » ne se distinguent pas : rien ne renseigne sur le fil d'autrui.
  IF NOT EXISTS (SELECT 1 FROM public.library_conversation_participants p
                  WHERE p.conversation_id = p_conversation_id AND p.library_id = p_library_id) THEN
    RAISE EXCEPTION 'not_participant' USING errcode = '42501', hint = 'error.correspondance.not_participant';
  END IF;
  v_id := public.fn_correspondance_poser_message(p_conversation_id, p_library_id, p_corps, p_lang);
  PERFORM api.fn_correspondance_lue(p_conversation_id);
  RETURN v_id;
END;
$$;

-- Archiver (ou rouvrir) un fil pour MA bibliothèque ; les autres ne le voient pas.
CREATE OR REPLACE FUNCTION api.fn_correspondance_archiver(p_conversation_id bigint, p_library_id uuid, p_archiver boolean DEFAULT true)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
BEGIN
  IF NOT public.fn_correspondance_coordonne(p_library_id) THEN
    RAISE EXCEPTION 'not_coordinator' USING errcode = '42501', hint = 'error.correspondance.not_coordinator';
  END IF;
  UPDATE public.library_conversation_participants
     SET archived_at = CASE WHEN p_archiver THEN now() ELSE NULL END
   WHERE conversation_id = p_conversation_id AND library_id = p_library_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'not_participant' USING errcode = '42501', hint = 'error.correspondance.not_participant';
  END IF;
END;
$$;

-- Marquer lu : jusqu'au dernier message du fil, pour MOI (coordination d'une
-- bibliothèque du fil). Rend l'identifiant du dernier message lu.
CREATE OR REPLACE FUNCTION api.fn_correspondance_lue(p_conversation_id bigint)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER
SET search_path TO 'public', 'pg_temp'
AS $$
DECLARE v_dernier bigint;
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT public.fn_correspondance_lit(p_conversation_id) THEN
    RAISE EXCEPTION 'not_participant' USING errcode = '42501', hint = 'error.correspondance.not_participant';
  END IF;
  SELECT coalesce(max(m.id), 0) INTO v_dernier FROM public.library_messages m WHERE m.conversation_id = p_conversation_id;
  INSERT INTO public.library_conversation_reads (conversation_id, user_id, last_read_message_id, read_at)
  VALUES (p_conversation_id, (SELECT auth.uid()), v_dernier, now())
  ON CONFLICT (conversation_id, user_id) DO UPDATE
    SET last_read_message_id = GREATEST(public.library_conversation_reads.last_read_message_id, EXCLUDED.last_read_message_id),
        read_at = now();
  RETURN v_dernier;
END;
$$;

