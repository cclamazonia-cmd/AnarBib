-- ── 7. La garde de publication ───────────────────────────────────────────
do $$
declare
  v_def text;
  v_new text;
  v_old text;
  v_rep text;
begin
  select pg_get_functiondef(p.oid) into v_def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'publish_book_draft'
     and pg_get_function_identity_arguments(p.oid) = 'p_draft_id bigint';
  if v_def is null then
    raise exception 'publish_book_draft(bigint) introuvable';
  end if;
  if position('error.publish.review_required' in v_def) > 0 then
    raise notice 'publish_book_draft porte deja la garde de revision — rien a faire';
    return;
  end if;

  v_old := E'  if v_draft.status = \'cancelled\' then\n'
        || E'    raise exception \'rascunho_descartado\' using hint = \'error.publish.draft_cancelled\';\n'
        || E'  end if;\n';
  v_rep := v_old
        || E'\n'
        || E'  -- 05/09/2026 : un lot ne d''un import ne se publie qu''apres une revision\n'
        || E'  -- approuvee par l''administration du reseau (catalog_batch_reviews).\n'
        || E'  -- publish_catalog_batch passe ici pour chaque brouillon : la garde le couvre.\n'
        || E'  if v_draft.batch_id is not null\n'
        || E'     and public.fn_batch_is_imported(v_draft.batch_id)\n'
        || E'     and public.fn_batch_review_status(v_draft.batch_id) is distinct from \'approved\' then\n'
        || E'    raise exception \'lote_importado_sem_revisao\' using hint = \'error.publish.review_required\';\n'
        || E'  end if;\n';
  if position(v_old in v_def) = 0 then
    raise exception 'publish_book_draft : l''ancre « rascunho_descartado » est absente — relire la definition avant de substituer';
  end if;
  v_new := replace(v_def, v_old, v_rep);
  if v_new = v_def then
    raise exception 'publish_book_draft : substitution non appliquee';
  end if;
  execute v_new;
end
$$;

-- ── 8. La cloche ─────────────────────────────────────────────────────────
create or replace function public.fn_catalog_batch_reviews_notify()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  -- Demande deposee : les admins reseau actifs, sauf la personne qui demande
  -- (une admin qui demande pour son propre lot n'a pas a etre prevenue).
  if tg_op = 'INSERT' and new.status = 'requested' then
    insert into public.user_notifications
      (user_id, library_id, category, title, body, link_type, link_id, is_read)
    select na.user_id, null, 'catalog',
           'notif.review.requested.title',
           'notif.review.requested.body',
           'batch_review_verdict', new.batch_id::text, false
      from public.network_administrators na
     where na.status = 'active'
       and na.user_id is distinct from new.requested_by;
    return new;
  end if;

  -- Verdict rendu : la personne qui a demande, elle seule.
  if tg_op = 'UPDATE' and new.status in ('approved', 'changes_requested')
     and old.status is distinct from new.status and new.requested_by is not null then
    insert into public.user_notifications
      (user_id, library_id, category, title, body, link_type, link_id, is_read)
    values (new.requested_by, null, 'catalog',
            case when new.status = 'approved' then 'notif.review.approved.title' else 'notif.review.changes.title' end,
            case when new.status = 'approved' then 'notif.review.approved.body'  else 'notif.review.changes.body'  end,
            'batch_review_result', new.batch_id::text, false);
    return new;
  end if;

  return new;
end;
$function$;

revoke execute on function public.fn_catalog_batch_reviews_notify() from public, anon, authenticated;

drop trigger if exists catalog_batch_reviews_notify on public.catalog_batch_reviews;
create trigger catalog_batch_reviews_notify
  after insert or update on public.catalog_batch_reviews
  for each row execute function public.fn_catalog_batch_reviews_notify();

-- ── 9. Verification structurelle (aucune dependance aux donnees) ─────────
do $verif$
declare
  v_def text;
  v_n int;
begin
  if to_regclass('public.catalog_batch_reviews') is null then
    raise exception 'catalog_batch_reviews introuvable';
  end if;
  select count(*) into v_n from pg_indexes
   where schemaname = 'public' and tablename = 'catalog_batch_reviews'
     and indexdef like '%(batch_id)%';
  if v_n = 0 then raise exception 'index sur catalog_batch_reviews.batch_id absent'; end if;

  select pg_get_functiondef(p.oid) into v_def
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.proname = 'publish_book_draft';
  if position('error.publish.review_required' in v_def) = 0 then
    raise exception 'publish_book_draft ne porte pas la garde de revision';
  end if;

  select count(*) into v_n from information_schema.routine_privileges
   where routine_schema = 'public'
     and routine_name in ('fn_batch_is_imported', 'fn_batch_review_status', 'fn_batch_review_report',
                          'fn_batch_review_request', 'fn_batch_review_verdict', 'fn_batch_reviews_list',
                          'fn_catalog_batch_reviews_notify')
     and grantee in ('anon', 'PUBLIC');
  if v_n <> 0 then raise exception '% droit(s) anon/PUBLIC de trop sur les fonctions de revision', v_n; end if;

  select count(*) into v_n from information_schema.table_privileges
   where table_schema = 'public' and table_name = 'catalog_batch_reviews'
     and grantee in ('anon', 'PUBLIC');
  if v_n <> 0 then raise exception 'catalog_batch_reviews ouverte a anon/PUBLIC'; end if;

  if not exists (select 1 from pg_trigger where tgname = 'catalog_batch_reviews_notify') then
    raise exception 'trigger catalog_batch_reviews_notify absent';
  end if;

  raise notice 'Paquet revision-des-lots-importes : verifications OK';
end
$verif$;

commit;
